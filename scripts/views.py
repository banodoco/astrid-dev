MARKER_PREFIX = "<!-- Generated by Astrid Dev view: "


def View(name: str, sources: tuple[str, ...], target: str,
         render: Callable[[Path], str], region: bool | str | None = False) -> _OttoView:
    """Bind the legacy Dev constructor to Otto's string-region view type."""
    if region is True:
        region = "vision-summary"
    elif region is False:
        region = None
    return _OttoView(name, sources, target, render, region, marker_prefix=MARKER_PREFIX)


