def check_view(view: _OttoView, root: Path) -> list[str]:
    return _otto_views.check_view(view, root, hint="run python3 scripts/astrid_dev.py sync",
                                  generic=False)


def check(root: Path) -> list[str]:
    declared, errors = views_for(root)
    return [*errors, *(message for view in declared for message in check_view(view, root))]


def sync(root: Path) -> list[str]:
    root = root.resolve()
    declared, errors = views_for(root)
    if errors:
        raise ValueError("shared blocks: " + "; ".join(errors))
    return _otto_views.sync(root, declared)


BLOCK_COPY_ROOTS = ("agent/", "templates/", "docs/")
BLOCK_COPY_HISTORY = ("docs/ledger/", "docs/handoffs/")


def block_views(root: Path) -> tuple[tuple[_OttoView, ...], list[str]]:
    """Return one View per `block:<name>` copy region of tracked Markdown, and the errors found.

    Each copy is filled from the single `block-source:<name>` owner region. Problems are returned,
    never raised, so one bad marker cannot stop unrelated checks.
    """
    root = root.resolve()
    try:
        listing = subprocess.run(["git", "ls-files", "-z", "*.md"], cwd=root, check=True, capture_output=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return (), []
    owners: dict[str, list[str]] = {}
    copies: list[tuple[str, str]] = []
    errors: list[str] = []
    for path in sorted(p for p in listing.decode("utf-8").split("\0") if p):
        full = root / path
        if full.is_symlink() or not full.is_file():
            continue
        try:
            regions = _block_regions(full.read_text(encoding="utf-8"), path)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        for kind, name in regions:
            if kind == "block-source":
                owners.setdefault(name, []).append(path)
                if ("block", name) in regions:
                    errors.append(f"{path}: block {name} has a copy region inside its own owner file; remove the block:{name} region")
            elif not path.startswith(BLOCK_COPY_ROOTS) or path.startswith(BLOCK_COPY_HISTORY):
                errors.append(f"{path}: block {name} copy is not allowed here; put copies only under agent/, templates/ or docs/, "
                              "never in docs/ledger/ or docs/handoffs/ (history)")
            else:
                copies.append((name, path))
    for name, paths in sorted(owners.items()):
        if len(paths) > 1:
            errors.append(f"block {name}: {len(paths)} owners ({', '.join(paths)}); keep exactly one block-source:{name} region")
    result = []
    for name, path in copies:
        if name not in owners:
            errors.append(f"{path}: block {name} has no owner; add a block-source:{name} region to the file that owns the rule")
        elif len(owners[name]) == 1 and path != owners[name][0]:
            result.append(View(f"block-{name}-{path}", (owners[name][0],), path,
                               lambda root, name=name, owner=owners[name][0], path=path: _render_block(root, name, owner, path),
                               f"block:{name}"))
    return tuple(result), errors


def _agent_routing_errors(root: Path, documents, blocks: tuple[_OttoView, ...] | None) -> list[str]:
    """Refuse authored policy copies; generated regions need one verified owner.

    Their content is checked by check_view and replaced by sync. Preflight must
    still permit regeneration after the canonical policy changes.
    """
    owner = f"{AGENT_SOURCE_ROOT}/shared/run-contract.md"
    texts = {(Path(AGENT_SOURCE_ROOT) / doc.relative).as_posix():
             doc.path.read_text(encoding="utf-8") for doc in documents}
    errors = []
    if len(routing_table_headers(texts.get(owner, ""))) != 1:
        errors.append(f"{owner}: route policy must have exactly one route-to-model-family table")
    for path, text in texts.items():
        headers = routing_table_headers(text)
        if path == owner or not headers:
            continue
        if blocks is None:
            blocks, _ = block_views(root)
        copies = [view for view in blocks if view.target == path
                  and view.region == "block:routing" and view.sources == (owner,)]
        valid_copy = False
        if len(copies) == 1:
            region = _block_regions(text, path).get(("block", "routing"))
            valid_copy = (region is not None
                          and all(region[1] <= offset < region[2] for offset in headers))
        if not valid_copy:
            errors.append(f"{path}: competing route-to-model-family table; "
                          f"link directly to {owner}#routing-and-bindings instead")
    return errors


def agent_index_errors(root: Path, blocks: tuple[_OttoView, ...] | None = None) -> list[str]:
    """Preflight every canonical index before any generated target is written."""
    declared = tuple(view for view in VIEWS
                     if (view.target in ROLE_INDEX_TARGETS and view.region == "workstreams")
                     or (view.target == "agent/README.md" and view.region == "shared-workstreams"))
    if not declared:
        return []  # A caller may select only unrelated views.
    root = root.resolve()
    try:
        documents = discover_documents(root)
        targets = {view.target for view in declared if view.region == "workstreams"}
        errors = []
        for document in documents:
            if document.kind == "workstream" and document.relative.parts[0] == "roles":
                role = document.relative.parts[1]
                parent = f"{AGENT_SOURCE_ROOT}/roles/{role}.md"
                if parent not in targets:
                    errors.append(f"{AGENT_SOURCE_ROOT}/{document.relative.as_posix()}: unregistered parent {parent}; "
                                  "declare its generated index target before adding workstreams")
        for view in declared:
            try:
                _index_parts((root / view.target).read_text(encoding="utf-8"), view.target, view.region)
            except (OSError, UnicodeError, ValueError) as exc:
                errors.append(str(exc))
        errors.extend(_agent_routing_errors(root, documents, blocks))
        return errors
    except (OSError, UnicodeError, ValueError) as exc:
        return [f"agent indexes: {exc}"]


def views_for(root: Path) -> tuple[tuple[_OttoView, ...], list[str]]:
    """The declared views plus the shared-block copies found under `root`, and any block errors."""
    found, errors = block_views(root)
    return tuple(VIEWS) + found, [*errors, *agent_index_errors(root, found)]
