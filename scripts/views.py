def _agent_index(root: Path, target: str) -> str:
    """Render navigation from the same parsed documents used by skill builds."""
    root = root.resolve()
    documents = discover_documents(root)
    shared = target == "agent/README.md"
    region = "shared-workstreams" if shared else "workstreams"
    source_folder = Path("shared/workstreams") if shared else Path("roles") / Path(target).stem
    before, after = _index_parts((root / target).read_text(encoding="utf-8"), target, region)
    rows = []
    for document in documents:
        if document.kind != "workstream" or document.relative.parent != source_folder:
            continue
        title = re.sub(r"([\\\[\]])", r"\\\1", document.title)
        link = quote(Path(os.path.relpath(document.path, (root / target).parent)).as_posix(), safe="/")
        row = f"- [{title}]({link})"
        rows.append(row if shared else row + f" — {document.description}")
    return before + f"<!-- {region}:start -->\n" + "\n".join(rows) + f"\n<!-- {region}:end -->" + after


