"""Bind Dev's Markdown-first document reader and skill configuration to Otto."""
from __future__ import annotations

from pathlib import Path

from otto.config import load_workspace
from otto.skills import SkillConfig
from otto.skills import documents
from otto.skills.documents import AgentDocument, SKILL_NAME_MAX_LENGTH, routing_table_headers


# Read the declaration of this checkout, not the temporary source trees used
# by callers. Skill configuration needs no registered checks or adapters.
_workspace = load_workspace(Path(__file__).resolve().parents[1], validate_registrations=False)
SKILL_CONFIG = SkillConfig(
    namespace=_workspace.skill_namespace,
    source_root=_workspace.paths["agent"].relative_to(_workspace.root),
    output=_workspace.paths["skills_output"].relative_to(_workspace.root),
    generated_header=(
        "<!-- GENERATED from {source} by `python3 scripts/astrid_dev.py skills build`. "
        "Do not edit this file: edit the source and rebuild. -->"
    ),
    lock_name_override=".skills-build.lock",
    lock_stage_prefix_override=".skills-lock-",
    probe_stage_prefix_override=".skills-probe-",
    build_stage_prefix_override=".skills-build-",
    legacy_owned_dirs=(Path("skills"),),
    legacy_retire_names=("astrid-dev", "shared"),
    path_based_link_ownership=True,
)

AGENT_SOURCE_ROOT = SKILL_CONFIG.source_root.as_posix()
SKILL_PREFIX = SKILL_CONFIG.namespace


def parse_document(root: Path, path: Path) -> AgentDocument:
    return documents.parse_document(root, path, SKILL_CONFIG)


def discover_documents(root: Path) -> tuple[AgentDocument, ...]:
    return documents.discover_documents(root, SKILL_CONFIG)


def validate_documents(root: Path) -> list[str]:
    return documents.validate_documents(root, SKILL_CONFIG)
